/*
算法：二进制中 1 的个数
简介：每次清除最低位的 1，统计无符号整数的置位数。
复杂度：时间 O(置位数)，空间 O(1)。
约定：使用 64 位无符号整数；0 的结果为 0。
*/
#include <cstdint>
#include <iostream>

using namespace std;

// ==================== 算法模板 ====================
// 作用：统计二进制中 1 的个数；输入：64 位无符号整数 x；输出：置位数，x=0 时返回 0。
int popcount(uint64_t x) {
    int cnt = 0;
    for (; x != 0; x &= x - 1) cnt++;
    return cnt;
}

// ==================== 使用示例 ====================
// 作用：演示位计数；输入：无，使用 0b101101；输出：4。
int main() {
    cout << popcount(0b101101ULL) << '\n'; // 4
}
